type Ctx = Pick<AuthContext, "userId" | "organizationId" | "orgRole"> & { user: { displayName: string } };
type Ev = { text: string };

/** Key points as plain lines (the stored summary is a markdown bullet list). */
const points = (content: string) => content.split("\n").map((l) => l.replace(/^[-•*]\s*/, "").trim()).filter(Boolean);
/** Summary text comes from what people said: strip anything that could be a link or contact in an SMS. */
const smsSafe = (s: string) => s.replace(/\b(?:https?:\/\/|www\.)\S+/gi, "").replace(/\S+@\S+\.\S+/g, "").replace(/\+?\d[\d\s-]{7,}\d/g, "").replace(/\s+/g, " ").trim();

function renderEmail(m: { title: string; when: string }, s: { points: string[]; decisions: Ev[]; actions: { description: string; owner: string | null; due: string | null }[]; issues: Ev[] }, link: string) {
  const section = (title: string, items: string[]) => (items.length ? `${title}\n${items.map((i) => `• ${i}`).join("\n")}\n\n` : "");
  const actions = s.actions.map((a) => `${a.description}${a.owner ? ` — ${a.owner}` : ""}${a.due ? ` (due ${a.due})` : ""}`);
  const text =
    `Call summary: ${m.title}\n${m.when}\n\n` +
    section("Key discussion points", s.points) +
    section("Decisions", s.decisions.map((d) => d.text)) +
    section("Action items", actions) +
    section("Open questions", s.issues.map((i) => i.text)) +
    `Full transcript and summary: ${link}\n\nThis summary was generated by AI from the call transcript; every item is linked to what was said.`;
  const h = (title: string, items: string[]) => (items.length ? `<h3 style="margin:16px 0 6px">${escapeHtml(title)}</h3><ul>${items.map((i) => `<li>${escapeHtml(i)}</li>`).join("")}</ul>` : "");
  const html =
    `<div style="font-family:system-ui,sans-serif;max-width:640px"><h2 style="margin:0">Call summary: ${escapeHtml(m.title)}</h2><p style="color:#666">${escapeHtml(m.when)}</p>` +
    h("Key discussion points", s.points) + h("Decisions", s.decisions.map((d) => d.text)) + h("Action items", actions) + h("Open questions", s.issues.map((i) => i.text)) +
    `<p><a href="${escapeHtml(link)}">Open the full transcript and summary</a></p><p style="color:#888;font-size:12px">Generated by AI from the call transcript; every item is linked to what was said.</p></div>`;
  return { text, html };
}

/**
 * Deliver a call summary to everyone who was in the call: in the app always, by email unless they
 * turned it off, and by SMS only to a verified number if they asked for it. Every attempt is recorded.
 */
export async function deliverSummary(meetingId: string, opts: { summaryId?: string; actorUserId?: string | null } = {}) {
  const meeting = await db.meeting.findUniqueOrThrow({
    where: { id: meetingId },
    select: {
      id: true, title: true, joinCode: true, hostId: true, organizationId: true, timezone: true, startedAt: true, endedAt: true,
      participants: { where: { removedAt: null }, select: { userId: true } },
    },
  });
  const summary = await db.meetingSummary.findFirst({
    where: { meetingId, ...(opts.summaryId ? { id: opts.summaryId } : {}) },
    orderBy: { createdAt: "desc" },
    include: { actionItems: { include: { assignee: { select: { displayName: true } } }, orderBy: { sourceStartMs: "asc" } } },
  });
  if (!summary) throw new AppError("NOT_FOUND", "This call has no summary yet.");

  const ids = [...new Set([meeting.hostId, ...meeting.participants.map((p) => p.userId)])];
  const people = await db.user.findMany({
    where: { id: { in: ids }, isActive: true },
    select: { id: true, email: true, displayName: true, timezone: true, summaryEmail: true, summarySms: true, phoneNumber: true, phoneVerifiedAt: true, phoneVerifiedVia: true },
  });
  const link = appUrl(`/meetings/${meeting.joinCode}/transcript`);
  const content = {
    points: points(summary.content),
    decisions: summary.decisions as unknown as Ev[],
    actions: summary.actionItems.map((a) => ({ description: a.description, owner: a.assignee?.displayName ?? a.assigneeName, due: a.dueDate ? a.dueDate.toISOString().slice(0, 10) : null })),
    issues: summary.openIssues as unknown as Ev[],
  };

  const rows: { userId: string; channel: "IN_APP" | "EMAIL" | "SMS"; status: "SENT" | "OUTBOX" | "FAILED" | "SKIPPED"; detail?: string }[] = [];
  for (const u of people) {
    await notifyUsers([u.id], {
      type: "summary.ready",
      title: `Call summary: ${meeting.title}`,
      body: `${content.points.length} key point(s) · ${content.decisions.length} decision(s) · ${content.actions.length} action item(s)`,
      link: `/meetings/${meeting.joinCode}/transcript`,
      data: { meetingId: meeting.id },
    });
    rows.push({ userId: u.id, channel: "IN_APP", status: "SENT", detail: "Notification and summary page" });

    if (!u.summaryEmail) rows.push({ userId: u.id, channel: "EMAIL", status: "SKIPPED", detail: "Turned off in their profile" });
    else {
      const when = meeting.startedAt ? meeting.startedAt.toLocaleString("en-GB", { timeZone: u.timezone, dateStyle: "medium", timeStyle: "short" }) : "";
      const r = await sendLoggedEmail({ userId: u.id, to: u.email, subject: `Call summary: ${meeting.title}`, purpose: "summary", ...renderEmail({ title: meeting.title, when }, content, link) });
      rows.push({ userId: u.id, channel: "EMAIL", status: r.status, detail: r.ok ? (r.status === "OUTBOX" ? "Development outbox (not sent)" : `To ${u.email}`) : r.error });
    }

    if (!u.summarySms) rows.push({ userId: u.id, channel: "SMS", status: "SKIPPED", detail: "Not requested" });
    else if (!canTextUser(u)) rows.push({ userId: u.id, channel: "SMS", status: "SKIPPED", detail: "No verified mobile number" });
    else {
      const top = content.points.slice(0, 2).map(smsSafe).filter(Boolean).join("; ");
      const body = `MeetMind call summary — ${smsSafe(meeting.title)}: ${top}`.slice(0, 260) + ` Full notes: ${link}`;
      const r = await sendSms({ userId: u.id, to: u.phoneNumber!, body, purpose: "summary" });
      rows.push({ userId: u.id, channel: "SMS", status: r.status, detail: r.ok ? (r.status === "OUTBOX" ? "Development outbox (not sent)" : `To ${u.phoneNumber}`) : r.error });
    }
  }
  await db.summaryDelivery.createMany({ data: rows.map((r) => ({ ...r, meetingId: meeting.id, summaryId: summary.id })) });
  await audit({ action: "summary.deliver", actorUserId: opts.actorUserId ?? null, organizationId: meeting.organizationId, targetType: "Meeting", targetId: meeting.id, metadata: { summaryId: summary.id, people: people.length, automatic: !opts.actorUserId } });
  return rows;
}

/** Who got the latest summary, how, and when (participants of the call only). */
export async function getDeliveries(ctx: Ctx, ref: string) {
  const { meeting, myRole } = await getTranscriptMeeting(ctx, ref);
  const summary = await db.meetingSummary.findFirst({ where: { meetingId: meeting.id }, orderBy: { createdAt: "desc" }, select: { id: true } });
  const rows = summary
    ? await db.summaryDelivery.findMany({ where: { summaryId: summary.id }, orderBy: { createdAt: "desc" }, include: { user: { select: { displayName: true, email: true } } } })
    : [];
  const latest = new Map<string, (typeof rows)[number]>();
  for (const r of rows) if (!latest.has(`${r.userId}:${r.channel}`)) latest.set(`${r.userId}:${r.channel}`, r);
  const byPerson = new Map<string, { userId: string; name: string; email: string; channels: Record<string, { status: string; detail: string | null; at: Date }> }>();
  for (const r of latest.values()) {
    const p = byPerson.get(r.userId) ?? { userId: r.userId, name: r.user.displayName, email: r.user.email, channels: {} };
    p.channels[r.channel] = { status: r.status, detail: r.detail, at: r.createdAt };
    byPerson.set(r.userId, p);
  }
  return {
    summaryId: summary?.id ?? null,
    canSend: (myRole === "HOST" || myRole === "COHOST") && !!summary,
    channels: { email: mailMode(), sms: getSmsProvider()?.name ?? "off" },
    people: [...byPerson.values()].sort((a, b) => a.name.localeCompare(b.name)),
  };
}

/** Host or co-host sends (or resends) the latest summary to everyone. */
export async function sendSummaryNow(ctx: Ctx, ref: string) {
  const { meeting, myRole } = await getTranscriptMeeting(ctx, ref);
  if (myRole !== "HOST" && myRole !== "COHOST") throw new AppError("FORBIDDEN", "Only the host or a co-host can send the summary.");
  rateLimit(`summary-send:${meeting.id}`, 5, 3600_000);
  await deliverSummary(meeting.id, { actorUserId: ctx.userId });
  return getDeliveries(ctx, ref);
}

/** Each person chooses how they receive call summaries (in the app always). */
export async function setSummaryPrefs(ctx: { userId: string }, raw: unknown) {
  const input = z.object({ email: z.boolean(), sms: z.boolean() }).parse(raw);
  const u = await db.user.findUniqueOrThrow({ where: { id: ctx.userId }, select: { phoneNumber: true, phoneVerifiedAt: true, phoneVerifiedVia: true } });
  if (input.sms && (!isSmsAvailable() || !canTextUser(u))) throw new AppError("VALIDATION", "Verify your mobile number first.");
  await db.user.update({ where: { id: ctx.userId }, data: { summaryEmail: input.email, summarySms: input.sms } });
  return input;
}
